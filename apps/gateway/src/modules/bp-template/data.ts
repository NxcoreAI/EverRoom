/** 发展阶段档位（标准"不同发展阶段的内容调整"，按已验证程度而非轮次）。 */
export type BpStage = "early" | "growth" | "mature";

/** 通用模块定义：标准每个 M 小节的四段固定结构。 */
export interface BpModuleDef {
  id: BpModuleId;
  title: string;
  /** 要回答：让读者理解什么。 */
  question: string;
  /** 应填内容。 */
  content: string;
  /** 证据与图表（含建议展示）。 */
  evidence: string;
  /** 检查重点（避免什么），整句转录。 */
  pitfalls: string;
}

/** 赛道对某模块的专项要求（标准每个 T 表格的一行）。 */
export interface BpTrackModuleOverride {
  required: string;
  evidenceHints: string[];
}

/** 赛道模板定义（标准每个 T 小节）。 */
export interface BpTrackDef {
  id: BpTrackId;
  name: string;
  /** 适用范围与交叉项目归口说明。 */
  intro: string;
  /** 核心判断。 */
  coreQuestion: string;
  /** 建议顺序：13 个模块的一个排列。 */
  moduleOrder: BpModuleId[];
  /** 赛道专项：本类必须填充的内容与常用图表。 */
  overrides: Partial<Record<BpModuleId, BpTrackModuleOverride>>;
  /** 优先指标。 */
  metrics: string;
  /** 常见错误。 */
  antiPatterns: string[];
}

/** X01 资产运营扩展模块（标准"资产运营扩展与行业专项"表）。 */
export interface BpX01Module {
  id: string;
  required: string;
  evidenceHints: string[];
}

/** 讲述顺序（标准"四种可复用的讲述顺序"表；顺序语义为文字规则，由选型结合赛道顺序落地）。 */
export interface BpNarrativeOrder {
  evidencePattern: string;
  orderNote: string;
}

/** 发展阶段调整维度（标准"不同发展阶段的内容调整"表）。 */
export interface BpStageTuning {
  dimension: string;
  early: string;
  growth: string;
  mature: string;
}

/** 专项叠加（标准"主模板之外按需叠加的专项"表）。 */
export interface BpAddon {
  id: string;
  name: string;
  requirements: string;
}

