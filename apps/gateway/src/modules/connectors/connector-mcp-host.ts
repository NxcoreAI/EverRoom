/**
 * Connector MCP host：Agent 与 oo 之间的工具面。
 *
 * - 本地工具：connector_query / connector_read（Query 层，只读）
 * - oo 工具：list_apps / list_connections / search_actions /
 *   get_action_guide / execute_action（转发到 oo /mcp）
 * - execute_action 只读守卫：非只读 action 直接拒绝（v1 不做写操作）
 *
 * 无状态：每个 JSON-RPC 请求独立处理；token 在 URL path 上，由 listener 校验。
 */

export interface McpToolDefinition {
  name: string;
  title?: string;
  description: string;
  inputSchema: Record<string, unknown>;
  annotations?: Record<string, unknown>;
}

export interface ConnectorMcpSession {
  baseUrl: string;
  runtimeToken?: string;
}

export interface ConnectorMcpHostOptions {
  query: ConnectorQueryService;
  session: () => ConnectorMcpSession | null;
  fetchImpl?: typeof fetch;
  logger?: {
    info(bindings: Record<string, unknown>, message: string): void;
    warn(bindings: Record<string, unknown>, message: string): void;
  };
  upstreamTools?: readonly McpToolDefinition[];
  upstreamTimeoutMs?: number;
  /** 已断开的连接判定；execute_action 带 connectionName 时用它拦截。 */
  disconnected?: (service: string, connectionName: string) => boolean;
}

interface JsonRpcRequest {
  jsonrpc: "2.0";
  id?: string | number | null;
  method: string;
  params?: Record<string, unknown>;
}

type JsonRpcResponse =
  | { jsonrpc: "2.0"; id: string | number | null; result: unknown }
  | { jsonrpc: "2.0"; id: string | number | null; error: { code: number; message: string; data?: unknown } };

