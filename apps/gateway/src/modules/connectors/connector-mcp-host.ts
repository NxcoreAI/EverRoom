export function isReadOnlyAction(actionId: string): boolean {
  const action = actionId.trim().toLowerCase();
  if (!action) return false;
  const segments = action.split(/[._-]/).filter(Boolean);
  // 写动词优先：get_or_create / search_and_replace 这类混合命名按写处理。
  if (segments.some((segment) => WRITE_VERBS.has(segment))) return false;
  return segments.some((segment) => READ_VERBS.has(segment));
}

function textContent(text: string, isError = false): Record<string, unknown> {
  return {
    content: [{ type: "text", text }],
    ...(isError ? { isError: true } : {}),
  };
}

function jsonRpcError(id: string | number | null, code: number, message: string): JsonRpcResponse {
  return { jsonrpc: "2.0", id, error: { code, message } };
}

export class ConnectorMcpHost {
  private readonly fetchImpl: typeof fetch;
  private readonly upstreamTools: readonly McpToolDefinition[];
  private readonly upstreamTimeoutMs: number;

  constructor(private readonly options: ConnectorMcpHostOptions) {
    this.fetchImpl = options.fetchImpl ?? fetch;
    this.upstreamTools = options.upstreamTools ?? UPSTREAM_TOOLS;
    this.upstreamTimeoutMs = options.upstreamTimeoutMs ?? 30_000;
  }

  tools(): McpToolDefinition[] {
    return [...this.upstreamTools, ...LOCAL_TOOLS];
  }

  /** 处理一个 JSON-RPC message；通知类返回 null（不写响应）。 */
  async handle(message: JsonRpcRequest): Promise<JsonRpcResponse | null> {
    const id = message.id ?? null;
    if (message.jsonrpc !== "2.0" || typeof message.method !== "string") {
      return jsonRpcError(id, -32600, "Invalid Request");
    }
    switch (message.method) {
      case "initialize":
        return {
          jsonrpc: "2.0",
          id,
          result: {
            protocolVersion:
              typeof message.params?.protocolVersion === "string"
                ? message.params.protocolVersion
                : "2025-06-18",
            capabilities: { tools: { listChanged: false } },
            serverInfo: { name: "everroom-connectors", version: "0.1.0" },
          },
        };
      case "notifications/initialized":
      case "notifications/cancelled":
        return null;
      case "ping":
        return { jsonrpc: "2.0", id, result: {} };
      case "tools/list":
        return { jsonrpc: "2.0", id, result: { tools: this.tools() } };
      case "tools/call":
        return this.callTool(id, message.params);
      default:
        return jsonRpcError(id, -32601, `Method not found: ${message.method}`);
    }
  }

  private async callTool(
    id: string | number | null,
    params: Record<string, unknown> | undefined,
  ): Promise<JsonRpcResponse> {
    const name = typeof params?.name === "string" ? params.name : "";
    const args = params?.arguments && typeof params.arguments === "object" && !Array.isArray(params.arguments)
      ? (params.arguments as Record<string, unknown>)
      : {};
    if (!name) return jsonRpcError(id, -32602, "tools/call requires params.name");
    try {
      let result: Record<string, unknown>;
      if (name === "connector_query") {
        result = await this.callQuery(args);
      } else if (name === "connector_read") {
        result = await this.callRead(args);
      } else if (this.upstreamTools.some((tool) => tool.name === name)) {
        result = await this.callUpstream(name, args);
      } else {
        result = textContent(`Unknown tool: ${name}`, true);
      }
      return { jsonrpc: "2.0", id, result };
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      this.options.logger?.warn({ tool: name, error: message }, "connector mcp tool failed");
      return { jsonrpc: "2.0", id, result: textContent(message, true) };
    }
  }

  private async callQuery(args: Record<string, unknown>): Promise<Record<string, unknown>> {
    const concept = typeof args.concept === "string" ? args.concept : "";
    if (!concept.trim()) return textContent("connector_query requires a non-empty concept.", true);
    const terms = Array.isArray(args.terms)
      ? args.terms.filter((term): term is string => typeof term === "string")
      : undefined;
    const services = Array.isArray(args.services)
      ? args.services.filter((service): service is string => typeof service === "string")
      : undefined;
    const input: QueryInput = {
      concept,
      ...(terms && terms.length > 0 ? { terms } : {}),
      ...(services && services.length > 0 ? { services } : {}),
      ...(typeof args.since === "string" ? { since: args.since } : {}),
      ...(typeof args.until === "string" ? { until: args.until } : {}),
      ...(typeof args.limit === "number" ? { limit: args.limit } : {}),
    };
    const result: QueryResult = await this.options.query.query(input);
    const payload = {
      query: result.query,
      hits: result.hits,
      coverage: result.coverage,
      truncated: result.truncated,
      next:
        result.hits.length > 0
          ? "Call connector_read with a hit's ref to read its full content."
          : "No hits. Check coverage before telling the user there is no data.",
    };
    return textContent(JSON.stringify(payload, null, 2));
  }

  private async callRead(args: Record<string, unknown>): Promise<Record<string, unknown>> {
    const ref = typeof args.ref === "string" ? args.ref : "";
    if (!ref) return textContent("connector_read requires ref.", true);
    const read: QueryReadResult = await this.options.query.read(ref);
    const header = [
      read.title ? `# ${read.title}` : null,
      `source: ${read.service} / ${read.connection}`,
      read.url ? `url: ${read.url}` : null,
    ]
      .filter(Boolean)
      .join("\n");
    const suffix = read.truncated
      ? `\n\n---\n(内容已截断：共 ${read.totalChars} 字符，可继续分页读取)`
      : "";
    return textContent(`${header}\n\n${read.markdown}${suffix}`);
  }

  private async callUpstream(name: string, args: Record<string, unknown>): Promise<Record<string, unknown>> {
    if (name === "execute_action") {
      const actionId = typeof args.actionId === "string" ? args.actionId : "";
      if (!actionId) return textContent("execute_action requires actionId.", true);
      const connectionName = typeof args.connectionName === "string" ? args.connectionName : "";
      const service = actionId.split(".")[0] ?? "";
      if (connectionName && service && this.options.disconnected?.(service, connectionName)) {
        return textContent(
          `connection_disconnected: ${service}/${connectionName} 已被用户断开，不能再读取。请换一个连接或在连接器页面重新连接。`,
          true,
        );
      }
      if (!isReadOnlyAction(actionId)) {
        return textContent(
          `mutation_not_allowed: ${actionId} 看起来是写操作。当前版本只允许只读 action；` +
            "如需读取数据请用 connector_query / connector_read，或改用一个 get/list/search 类 action。",
          true,
        );
      }
    }
    const session = this.options.session();
    if (!session?.baseUrl?.trim()) {
      return textContent(
        "connector_not_connected: 连接层未登录或未就绪。请先在连接器页面登录并连接账号。",
        true,
      );
    }
    const headers: Record<string, string> = {
      "content-type": "application/json",
      accept: "application/json",
    };
    if (session.runtimeToken) headers.authorization = `Bearer ${session.runtimeToken}`;
    const response = await this.fetchImpl(`${session.baseUrl.replace(/\/+$/, "")}/mcp`, {
      method: "POST",
      headers,
      body: JSON.stringify({
        jsonrpc: "2.0",
        id: randomUUID(),
        method: "tools/call",
        params: { name, arguments: args },
      }),
      signal: AbortSignal.timeout(this.upstreamTimeoutMs),
    });
    const payload = (await response.json().catch(() => null)) as
      | { result?: Record<string, unknown>; error?: { message?: unknown } }
      | null;
    if (!response.ok && !payload) {
      throw new Error(`oo MCP 请求失败（HTTP ${response.status}）。`);
    }
    if (payload?.error) {
      throw new Error(typeof payload.error.message === "string" ? payload.error.message : "oo MCP 调用失败。");
    }
    const result = payload?.result;
    if (!result || typeof result !== "object") {
      throw new Error("oo MCP 返回了空结果。");
    }
    return result;
  }
}
